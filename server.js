// Middleware: lets Express understand incoming JSON data
app.use(express.json());

// Middleware: serves files from the public folder
app.use(express.static("public"));

// Middleware: logs each request in the VS Code terminal
app.use((req, res, next) => {
  console.log(`${req.method} ${req.url}`);
  next();
});

// About route
app.get("/about", (req, res) => {
  res.send(`
    <h1>About Okinawa Travel Destinations</h1>
    <p>This page was generated by Express.</p>
    <p><a href="/">Return Home</a></p>
  `);
});

// API route: returns ALL destinations as JSON
app.get("/api/destinations", (req, res) => {
  res.json(destinations);
});

// API route: returns ONE destination by its ID
app.get("/api/destinations/:id", (req, res) => {
  const id = Number(req.params.id);

  const destination = destinations.find(
    destination => destination.id === id
  );

  if (!destination) {
    return res.status(404).json({
      message: "Destination not found"
    });
  }

  res.json(destination);
});

// Start the server on localhost:3000
app.listen(PORT, () => {
  console.log(
    `Okinawa Travel Destinations running at http://localhost:${PORT}`
  );
});